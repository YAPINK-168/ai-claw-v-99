PRESETS = {
    "status": (0x03, [0x00]),
    "bill": (0x04, []),
    "param": (0x05, [0x01]),
    "takeover": (0x06, [0x01]),
    "release": (0x06, [0x00]),
    "free1": (0x07, [0x01]),
    "led5": (0x08, [0x05]),
    "led0": (0x08, [0x00]),
}


def crc16(data: list[int]) -> int:
    crc = 0
    for b in data:
        crc = (crc >> 8) ^ CRC16_TABLE[(crc ^ b) & 0xFF]
    return crc


def build_frame(cmd: int, data: list[int], sn: int = 1, rnd: int = 0) -> list[int]:
    body = [0x0A, 0x00, sn & 0xFF, rnd & 0xFF, cmd & 0xFF, *data]
    body[1] = len(body)
    c = crc16(body)
    return body + [c & 0xFF, (c >> 8) & 0xFF]


def selftest() -> int:
    # Known vector: status query sn=1 rnd=0 → length 6
    frame = build_frame(0x03, [0x00], sn=1, rnd=0)
    assert frame[0] == 0x0A
    assert frame[1] == 6
    assert frame[4] == 0x03
    body_crc = crc16(frame[:-2])
    got = frame[-2] | (frame[-1] << 8)
    assert body_crc == got, (hex(body_crc), hex(got), frame)
    # Echo-style takeover
    t = build_frame(0x06, [0x01], sn=2, rnd=0x55)
    assert t[1] == 6 and t[4] == 0x06 and t[5] == 0x01
    print("selftest OK")
    print("status:", " ".join(f"{b:02X}" for b in frame))
    print("takeover:", " ".join(f"{b:02X}" for b in t))
    return 0


def main() -> None:
    p = argparse.ArgumentParser(description="Generate claw-machine Android TX frames")
    p.add_argument("args", nargs="*", help="preset name, or: CMD [DATA...] hex")
    p.add_argument("--sn", type=lambda x: int(x, 0), default=1)
    p.add_argument("--rnd", type=lambda x: int(x, 0), default=0)
    p.add_argument("--selftest", action="store_true")
    ns = p.parse_args()

    if ns.selftest:
        sys.exit(selftest())

    if not ns.args:
        p.print_help()
        sys.exit(2)

    if len(ns.args) == 1 and ns.args[0].lower() in PRESETS:
        cmd, data = PRESETS[ns.args[0].lower()]
    else:
        cmd = int(ns.args[0], 16)
        data = [int(x, 16) for x in ns.args[1:]]

    frame = build_frame(cmd, data, ns.sn, ns.rnd)
    print(" ".join(f"{b:02X}" for b in frame))


if __name__ == "__main__":
    main()
